export function getGuideBySlug(slug: string): Guide | undefined {
  // Non-ASCII (Hebrew) dynamic segments sometimes arrive still percent-encoded
  // depending on the render path (build-time vs on-demand) — decode defensively.
  let decoded = slug;
  try { decoded = decodeURIComponent(slug); } catch { /* already decoded / not encoded */ }
  return GUIDES.find(g => g.slug === decoded || g.slug === slug);
}
